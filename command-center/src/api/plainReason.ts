/** Причина, когда фабрика её не назвала. */
export const FALLBACK_REASON = 'API запущен не на рабочей фабрике';

/**
 * Причина «только смотреть» простыми словами: пути к папкам — только под «подробнее»
 * (ROADMAP → Правила → «Для человека»), поэтому из строки фабрики они убираются — и в скобках
 * («копия разработки (/…/cc-api), а не …»), и голые. С договора 0.35.0 фабрика сама режет пути
 * (корень — `.../<имя>`, домашний каталог — `~`), их это тоже касается.
 */
export function plainReason(reason: string): string {
  const out = reason
    .replace(/\s*\([^()]*[/\\][^()]*\)/g, '')
    .replace(/\s*(?:~|\.{0,3})?\/[^\s,;)]+/g, '')
    .replace(/\s+([,;.])/g, '$1')
    .replace(/\s{2,}/g, ' ')
    .trim();
  return out || FALLBACK_REASON;
}
