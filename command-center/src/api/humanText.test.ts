import { byYou, humanDashes, humanDates, humanReason, withoutCodes } from './humanText';

const NOW = new Date('2026-10-10T07:00:00Z');

describe('строка фабрики для человека (CC-0089)', () => {
  it('дата без времени — «9 октября»; другой год — с годом; не дата — как есть', () => {
    expect(humanDates('батч вчерашний (2026-10-09)', NOW)).toBe('батч вчерашний (9 октября)');
    expect(humanDates('с 2025-12-31', NOW)).toBe('с 31 декабря 2025');
    expect(humanDates('код 2026-13-40', NOW)).toBe('код 2026-13-40');
  });

  it('дата и время с зоной и id батча — «10.10, 07:04» по Москве', () => {
    expect(humanDates('начат 2026-10-10T04:04:00Z', NOW)).toBe('начат 10.10, 07:04');
    expect(humanDates('в 2026-10-10T07:04:00.123+03:00.', NOW)).toBe('в 10.10, 07:04.');
    expect(humanDates('example-science 2026-10-10T0405Z был', NOW)).toBe(
      'example-science 10.10, 07:05 был',
    );
  });

  it('« - » между частями — тире; дефис в слове и минус — как есть', () => {
    expect(humanDashes('день прошёл - продолжать нельзя')).toBe('день прошёл — продолжать нельзя');
    expect(humanDashes('kill -9 и YouTube-квота')).toBe('kill -9 и YouTube-квота');
  });

  it('коды настроек в скобках убираются, обычные скобки — нет', () => {
    expect(withoutCodes('порог батча (batch_feed_days)')).toBe('порог батча');
    expect(withoutCodes('окно канала (ручной запуск — в любое время)')).toBe(
      'окно канала (ручной запуск — в любое время)',
    );
  });

  it('вместе: путь, дата, тире', () => {
    expect(
      humanReason(
        'батч вчерашний (2026-10-09): день батча прошёл (pipeline/example-film/x) - запустите новый',
        NOW,
      ),
    ).toBe('батч вчерашний (9 октября): день батча прошёл — запустите новый');
  });
});

describe('«пользователем (центр)» — «вами из центра» (CC-0115)', () => {
  it('остановка из центра — от вашего лица, в строке причины и в humanReason', () => {
    expect(byYou('остановлен пользователем (центр): ждёт «продолжить»')).toBe(
      'остановлен вами из центра: ждёт «продолжить»',
    );
    expect(humanReason('батч остановлен пользователем (центр)')).toBe(
      'батч остановлен вами из центра',
    );
    expect(byYou('остановлен оператором')).toBe('остановлен оператором');
  });
});
