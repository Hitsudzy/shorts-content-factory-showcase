/**
 * Какой таб активен на этом пути (CC-0085): сегмент области или `null`, если путь ни одной
 * области не принадлежит. Вложенные пути — своей области (`/channels/reel`, `/channels/new` →
 * «Каналы»); строка запроса и якорь не в счёт (`/questions?view=requests` → «Вопросы»);
 * Главная — только ровно `/`.
 */
export function activeAreaPath(location: string): string | null {
  const pathname = location.split(/[?#]/, 1)[0] ?? '';
  const first = pathname.split('/').find(Boolean);
  if (first === undefined) return '';
  return AREAS.some((a) => a.path !== '' && a.path === first) ? first : null;
}
