export const sectionOf = (id: SectionId): TourSection => SECTIONS.find((s) => s.id === id)!;

/** Шаги раздела в порядке тура. */
export const stepsOf = (id: SectionId): TourStep[] => STEPS.filter((s) => s.section === id);

/** Номер первого шага раздела. */
export const sectionStart = (id: SectionId): number => STEPS.findIndex((s) => s.section === id);

/** «3 из 34». */
export const stepLabel = (index: number, total = STEPS.length): string =>
  `${index + 1} из ${total}`;

/** Зритель уже на экране шага (у «глубоких» — и на вложенном пути). */
export function onRoute(step: TourStep, pathname: string): boolean {
  const path = pathname.replace(/\/+$/, '') || '/';
  if (path === step.route) return true;
  return !!step.deeper && path.startsWith(`${step.route}/`);
}
