// Шаги тура «Обучение» (CC-0072): по экранам центра в порядке табов, потом общие приёмы.
//
// Цель шага — элемент с атрибутом `data-tour="<target>"`. Если на живых данных его нет
// (пустая очередь, нет батча, ролик не открыт), шаг всё равно показывается и объясняет словами
// (`missing`). `open` — метка ссылки, по которой тур сам переходит, если цели нет (открыть
// первый канал, первый ролик): это только переход по ссылке, тур ничего не нажимает и не пишет.
//
// Тексты — для человека, который не программист: простым русским, без номеров и путей.

export type SectionId =
  'home' | 'channels' | 'batches' | 'videos' | 'publishing' | 'questions' | 'basics';

export type TourSection = { id: SectionId; title: string; about: string };

export type TourStep = {
  id: string;
  section: SectionId;
  /** Экран шага: если зритель не на нём, тур переходит сюда. */
  route: string;
  /** Подходит и путь глубже (`/channels/…` для экрана канала). */
  deeper?: boolean;
  /** `data-tour` подсвечиваемого элемента; нет — подсказка посреди экрана. */
  target?: string;
  /** `data-tour` ссылки, по которой перейти, если цели на экране нет. */
  open?: string;
  title: string;
  body: string[];
  /** Что сказать, если цели на экране сейчас нет. */
  missing?: string;
};

